// Builds /ar/index.html from /index.html and the Arabic copy (const AR) in assets/js/main.js,
// so the Arabic page has its own URL that search engines can index.
// Run from the website folder after editing either file:  node tools/build-ar.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const SITE = 'https://stacko-lb.com';
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'assets/js/main.js'), 'utf8');

// ---- Arabic copy from main.js ----
const arStart = js.indexOf('const AR={');
const arEnd = js.indexOf('\n};', arStart);
if (arStart < 0 || arEnd < 0) throw new Error('const AR={...}; not found in main.js');
const AR = new Function('return ' + js.slice(arStart + 'const AR='.length, arEnd + 2))();

// ---- swap every data-i element's content for its Arabic copy ----
const ranges = [];
for (const m of html.matchAll(/data-i="([^"]+)"/g)) {
  const key = m[1];
  if (!(key in AR)) throw new Error(`No Arabic copy for data-i="${key}"`);
  const start = html.lastIndexOf('<', m.index);
  const tag = /^<([a-zA-Z][a-zA-Z0-9]*)/.exec(html.slice(start))[1];
  const openEnd = html.indexOf('>', m.index) + 1;
  const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'g');
  re.lastIndex = openEnd;
  let depth = 1, close;
  while ((close = re.exec(html))) { depth += close[1] ? -1 : 1; if (!depth) break; }
  if (!close) throw new Error(`Unclosed <${tag} data-i="${key}">`);
  ranges.push({ from: openEnd, to: close.index, text: AR[key] });
}
ranges.sort((a, b) => b.from - a.from).forEach((r, i, all) => {
  if (i && r.to > all[i - 1].from) throw new Error('Nested data-i elements are not supported');
  html = html.slice(0, r.from) + r.text + html.slice(r.to);
});

// ---- page-level replacements (each must match exactly once) ----
const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const swap = (from, to) => {
  const n = html.split(from).length - 1;
  if (n !== 1) throw new Error(`Expected one match for: ${from.slice(0, 80)} (found ${n})`);
  html = html.replace(from, () => to);
};
const swapAttr = (selector, value) => {
  const re = new RegExp(`(${selector.replace(/[[\]]/g, '\\$&')}[^>]*content=")[^"]*"`);
  if (!re.test(html)) throw new Error('Meta not found: ' + selector);
  html = html.replace(re, (_, a) => a + esc(value) + '"');
};
const strip = s => s.replace(/<[^>]+>/g, '').replace(/&rlm;/g, '‏').replace(/&amp;/g, '&');

const T = {
  title: 'ستاكو | برنامج إدارة المستودعات والمخزون في لبنان والخليج',
  desc: 'تابع مخزونك في كل مستودع وفرع على خريطة حيّة واحدة. سجّل التحويلات من Telegram، وحوّل فواتير الموردين إلى مسودات يوافق عليها فريقك.',
  ogTitle: 'ستاكو | مخزونك دايماً قدّام عينك',
  ogDesc: 'كل مستودع وصنف وشحنة على خريطة حيّة واحدة، مع مسودات ذكاء اصطناعي يوافق عليها فريقك. مصمّم للموزّعين والمستوردين والمتاجر في لبنان والخليج.',
  alt: 'خريطة ليلية لشبكة مستودعات مع مسارات شحن مضيئة',
};

swap('<html lang="en" dir="ltr">', '<html lang="ar" dir="rtl">');
html = html.replace(/<!-- The Arabic page \/ar\/ is generated[^>]*-->/, '<!-- Generated by tools/build-ar.js from /index.html. Do not edit by hand. -->');
html = html.replace(/<title>[^<]*<\/title>/, `<title>${esc(T.title)}</title>`);
swapAttr('<meta name="description"', T.desc);
swap(`<link rel="canonical" href="${SITE}/">`, `<link rel="canonical" href="${SITE}/ar/">`);
swapAttr('<meta property="og:title"', T.ogTitle);
swapAttr('<meta property="og:description"', T.ogDesc);
swapAttr('<meta property="og:url"', `${SITE}/ar/`);
swapAttr('<meta property="og:image:alt"', T.alt);
swapAttr('<meta property="og:locale"', 'ar_LB');
swapAttr('<meta property="og:locale:alternate"', 'en_US');
swapAttr('<meta name="twitter:title"', T.ogTitle);
swapAttr('<meta name="twitter:description"', T.ogDesc);
swapAttr('<meta name="twitter:image:alt"', T.alt);
swap('<a class="lang-btn" id="langBtn" href="/ar/" hreflang="ar" lang="ar">العربية</a>',
     '<a class="lang-btn" id="langBtn" href="/" hreflang="en" lang="en">English</a>');
swap('<a href="/pricing/" data-i="navPricing">', '<a href="/ar/pricing/" data-i="navPricing">');

// ---- structured data: Arabic web page and FAQ ----
const ld = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(html);
const data = JSON.parse(ld[1]);
for (const node of data['@graph']) {
  if (node['@type'] === 'WebPage') Object.assign(node, { '@id': `${SITE}/ar/#webpage`, url: `${SITE}/ar/`, name: T.title, inLanguage: 'ar' });
  if (node['@type'] === 'FAQPage') {
    node.inLanguage = 'ar';
    node.mainEntity = node.mainEntity.map((_, i) => ({
      '@type': 'Question', name: strip(AR['q' + (i + 1)]),
      acceptedAnswer: { '@type': 'Answer', text: strip(AR['a' + (i + 1)]) },
    }));
  }
}
html = html.replace(ld[0], () => `<script type="application/ld+json">\n${JSON.stringify(data, null, 2)}\n</script>`);

fs.mkdirSync(path.join(root, 'ar'), { recursive: true });
fs.writeFileSync(path.join(root, 'ar/index.html'), html);
console.log(`ar/index.html written (${ranges.length} strings translated)`);
